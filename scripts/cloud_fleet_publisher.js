async function fetchSupabaseArticles(blogId, offset, limit) {
  const url = `${SUPABASE_URL}/rest/v1/articles?blog_id=eq.${blogId}&order=created_at.desc&offset=${offset}&limit=${limit}&select=id,title,slug,summary,content_markdown,content_html,tags`;
  
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: {
          'apikey': SERVICE_KEY,
          'Authorization': `Bearer ${SERVICE_KEY}`
        }
      });
      if (!res.ok) {
        throw new Error(`Supabase REST Error ${res.status}: ${await res.text()}`);
      }
      return await res.json();
    } catch (err) {
      if (attempt === 3) throw err;
      await new Promise(r => setTimeout(r, 2000));
    }
  }
}

