async function runPublisherCycle(batchSize = 15) {
  console.log(`\n======================================================`);
  console.log(`🚀 SEOGRAM Cloud Publisher Starting (Batch Size: ${batchSize})`);
  console.log(`   Time: ${new Date().toISOString()}`);
  console.log(`======================================================\n`);

  initCookies();
  const rozPanel = ensureRozblogLogin();
  const status = getStatus();

  console.log(`Current Status:`);
  console.log(`  • GitHub:  ${status.github || 1000} (Last drip: ${status.github_last_drip || 'Never'})`);
  console.log(`  • GitLab:  ${status.gitlab || 1000} (Last drip: ${status.gitlab_last_drip || 'Never'})`);
  console.log(`  • Blogfa:  ${status.blogfa_published}/${status.blogfa_total}`);
  console.log(`  • Rozblog: ${status.rozblog_published}/${status.rozblog_total}`);

  // 1. GitHub Pages Drip (Every 2 Hours)
  try {
    dripGitHubArticle(status);
  } catch (err) {
    console.error('GitHub drip error:', err.message);
  }

  // 2. GitLab Pages Drip (Every 2 Hours)
  try {
    await dripGitLabArticle(status);
  } catch (err) {
    console.error('GitLab drip error:', err.message);
  }

  // 3. Rozblog Batch
  if (status.rozblog_published < 1000) {
    console.log(`\n--- [Rozblog] Fetching next batch of ${batchSize} articles ---`);
    try {
      const rozArticles = await fetchSupabaseArticles(ROZ_BLOG_ID, status.rozblog_published, batchSize);
      console.log(`Fetched ${rozArticles.length} articles from Supabase.`);

      let rozSuccessCount = 0;
      for (let i = 0; i < rozArticles.length; i++) {
        const ok = publishRozblogArticle(rozPanel, rozArticles[i]);
        if (ok === 'DAILY_LIMIT') {
          break;
        }
        if (ok) {
          status.rozblog_published += 1;
          rozSuccessCount++;
          console.log(`✓ [Rozblog] (${status.rozblog_published}/1000) ${rozArticles[i].title.substring(0, 50)}...`);
        } else {
          console.log(`✗ [Rozblog] Failed: ${rozArticles[i].title.substring(0, 50)}...`);
        }
        await new Promise(r => setTimeout(r, 1200));
      }
      console.log(`Rozblog batch complete: +${rozSuccessCount} published.`);
    } catch (err) {
      console.error('Error in Rozblog cycle:', err.message);
    }
  } else {
    console.log('✓ Rozblog target of 1,000 articles already achieved!');
  }

  // 4. Blogfa Batch
  if (status.blogfa_published < 1000) {
    console.log(`\n--- [Blogfa] Fetching next batch of ${batchSize} articles ---`);
    try {
      const blogfaArticles = await fetchSupabaseArticles(BLOGFA_BLOG_ID, status.blogfa_published, batchSize);
      console.log(`Fetched ${blogfaArticles.length} articles from Supabase.`);

      let blogfaSuccessCount = 0;
      for (let i = 0; i < blogfaArticles.length; i++) {
        const ok = publishBlogfaArticle(blogfaArticles[i], i, status.blogfa_published);
        if (ok) {
          status.blogfa_published += 1;
          blogfaSuccessCount++;
          console.log(`✓ [Blogfa] (${status.blogfa_published}/1000) ${blogfaArticles[i].title.substring(0, 50)}...`);
        } else {
          console.log(`✗ [Blogfa] Failed: ${blogfaArticles[i].title.substring(0, 50)}...`);
        }
        await new Promise(r => setTimeout(r, 1200));
      }
      console.log(`Blogfa batch complete: +${blogfaSuccessCount} published.`);

      // Regenerate Blogfa cache
      try {
        execSync(`${CURL} -s -b "${BLOGFA_COOKIES}" -c "${BLOGFA_COOKIES}" --max-time 15 "https://blogfa.com/desktop/refreshblog.ashx?r=${Date.now()}"`, { timeout: 20000 });
        console.log('✓ Blogfa static cache refreshed.');
      } catch (e) {}
    } catch (err) {
      console.error('Error in Blogfa cycle:', err.message);
    }
  } else {
    console.log('✓ Blogfa target of 1,000 articles already achieved!');
  }

  status.last_updated = new Date().toISOString();
  saveStatus(status);

  console.log(`\n======================================================`);
  console.log(`🏁 Cycle Complete. Updated Status:`);
  console.log(JSON.stringify(status, null, 2));
  console.log(`======================================================\n`);
}

if (require.main === module) {
  const batch = parseInt(process.argv[2], 10) || 15;
  runPublisherCycle(batch).catch(err => {
    console.error('Fatal Publisher Error:', err);
    process.exit(1);
  });
}

module.exports = { runPublisherCycle };
